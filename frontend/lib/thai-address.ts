// Fallback & Quick Lookup Helpers
export function getAllProvinces(): string[] {
  return THAI_ADDRESS_DATA.map((p) => p.name);
}

export function getDistrictsByProvince(provinceName: string): string[] {
  if (!provinceName) return [];
  const found = THAI_ADDRESS_DATA.find((p) => p.name === provinceName.trim());
  return found ? found.districts.map((d) => d.name) : [];
}

export function getSubdistrictsByDistrict(provinceName: string, districtName: string): string[] {
  if (!provinceName || !districtName) return [];
  const foundProvince = THAI_ADDRESS_DATA.find((p) => p.name === provinceName.trim());
  if (!foundProvince) return [];
  const foundDistrict = foundProvince.districts.find((d) => d.name === districtName.trim());
  return foundDistrict ? foundDistrict.subdistricts : [];
}
